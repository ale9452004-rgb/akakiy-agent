"""
Навык 'project' для работы с кодовой базой и файлами проекта Акакия.
"""

import re
from typing import Optional

from skills.base import BaseSkill


PROJECT_SYSTEM_PROMPT = """Ты используешь специализированный навык 'project' для работы с проектом Акакия.
В твоём распоряжении проверенные инструменты исследования кодовой базы:
- list_files: получение списка файлов и директорий проекта;
- find_file: поиск файла по имени или относительному пути;
- read_file: чтение полного содержимого файла;
- search_files: поиск текста, определений функций, классов или фрагментов кода во всех файлах проекта;
- analyze_file: статический AST-анализ структуры файла (классы, функции, импорты).

Рекомендации по выполнению:
1. При вопросе о конкретной функции или классе сначала используй search_files или find_file.
2. Для изучения реализации читай конкретный файл через read_file.
3. Отвечай точно, опираясь исключительно на фактический код в проекте.
"""


class ProjectSkill(BaseSkill):
    """
    Навык работы с проектом Акакия.
    """

    name = "project"
    description = (
        "Работа с проектом: просмотр структуры, поиск файлов, чтение исходного кода, "
        "поиск текста и статический анализ."
    )
    tools = [
        "list_files",
        "find_file",
        "read_file",
        "search_files",
        "analyze_file"
    ]
    system_prompt = PROJECT_SYSTEM_PROMPT

    def __init__(self, enabled: bool = True):
        super().__init__(
            name=self.name,
            description=self.description,
            tools=self.tools,
            system_prompt=self.system_prompt,
            enabled=enabled
        )

    def matches(self, user_input: str) -> bool:
        """
        Детерминированно определяет, относится ли запрос к работе с файлами и кодом проекта.
        """
        if not user_input or not isinstance(user_input, str):
            return False

        norm = user_input.strip().lower()

        # Исключение: запросы к памяти не должны перехватываться
        if re.search(r"\b(?:запомни|памят[ьие]|вспомни|забудь)\b", norm):
            return False

        # Исключение: служебные команды планировщика
        if norm.startswith("план:") or norm in {"выполни план", "выполнить план", "покажи план", "очисти план"}:
            return False

        # Шаблоны поиска/чтения файлов и кода проекта
        project_patterns = [
            # Прямые упоминания проекта и файлов
            r"\b(?:в|по)\s+проекте\b",
            r"\bфайл[ыао]?\s+проекта\b",
            r"\bструктур[аеуы]\s+проекта\b",
            r"\bпоиск\s+по\s+проекту\b",

            # Действия над файлами
            r"\b(?:найди|найти|поищи|ищи)\s+(?:в\s+проекте\s+)?(?:файл|текст|функци[юия]|класс|метод)\b",
            r"\b(?:прочитай|покажи|открой)\s+файл\b",
            r"\b(?:проанализируй|анализ)\s+файл[а]?\b",
            r"\b(?:список|структур[аеуы])\s+файлов\b",

            # Поиск определений функций/классов или расположения
            r"\bгде\s+(?:объявлен[аоы]?|определен[аоы]?|находится|лежит|содержится)\b.*\b(?:класс|функци[яию]|метод|код)\b",
            r"\b(?:в\s+каком\s+файле|в\s+каких\s+файлах)\b",

            # Упоминания конкретных расширений файлов в контексте просмотра/поиска
            r"\b(?:покажи|прочитай|открой|код|строк[аие])\s+[a-zA-Z0-9_\-\./\\]+\.(?:py|json|md|txt|bat)\b",
        ]

        for p in project_patterns:
            if re.search(p, norm):
                return True

        return False
