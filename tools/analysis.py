from ollama_client import OllamaClient
from tools.files import read_file


def analyze_file(filename):
    content, error = read_file(filename)

    if error:
        return error

    ai = OllamaClient()

    prompt = (
        f"Проанализируй файл проекта `{filename}`.\n\n"
        "Твоя задача:\n"
        "1. Опиши назначение файла.\n"
        "2. Объясни, как он работает.\n"
        "3. Найди потенциальные ошибки и проблемы.\n"
        "4. Найди слабые места в архитектуре.\n"
        "5. Предложи конкретные улучшения.\n"
        "6. Если код уже написан хорошо, тоже укажи это.\n\n"
        "Важно:\n"
        "- Не изменяй код.\n"
        "- Не переписывай весь файл.\n"
        "- Анализируй именно предоставленное содержимое файла.\n"
        "- Не придумывай код или функции, которых нет в файле.\n"
        "- Отвечай структурированно и на русском языке.\n\n"
        "Содержимое файла:\n\n"
        "----- НАЧАЛО ФАЙЛА -----\n"
        f"{content}\n"
        "----- КОНЕЦ ФАЙЛА -----"
    )

    return ai.ask(prompt, add_to_history=False)