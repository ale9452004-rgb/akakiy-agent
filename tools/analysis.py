from ollama_client import OllamaClient
from tools.files import read_file


def analyze_file(
    filename,
    task="",
    content=None
):
    """
    Анализирует содержимое файла проекта.

    Если content уже передан, повторное чтение файла
    не выполняется.
    """

    if content is None:
        file_result = read_file(filename)

        if not isinstance(file_result, dict):
            return {
                "success": False,
                "message": (
                    "Инструмент чтения файла "
                    "вернул некорректный результат."
                )
            }

        if not file_result.get("success"):
            return {
                "success": False,
                "message": file_result.get(
                    "message",
                    "Не удалось прочитать файл."
                )
            }

        content = file_result.get("content")

    if content is None:
        return {
            "success": False,
            "message": (
                "Файл прочитан, но его содержимое "
                "отсутствует."
            )
        }

    ai = OllamaClient()

    prompt = f"""
Ты — технический анализатор кода.

Ты НЕ являешься чат-ассистентом.
Не задавай пользователю вопросы.
Не предлагай варианты помощи.
Не пиши приветствие.
Не объясняй, что ты можешь сделать.

Твоя единственная задача — проанализировать предоставленный
код и вернуть технический анализ.

Файл:
{filename}

Задача:
{task}

ВАЖНЫЕ ПРАВИЛА:

1. Анализируй только предоставленный код.

2. Если задача относится к конкретной функции,
   анализируй прежде всего эту функцию.

3. Не придумывай функции, переменные, файлы или поведение,
   которых нет в предоставленном коде.

4. Если функция вызывает другую функцию, но её код
   не предоставлен, нельзя утверждать, как именно
   работает вызываемая функция.

5. Не считай проблемой просто другой способ написания кода.

6. Не считай проблемой отсутствие функциональности,
   если из предоставленного кода не следует,
   что она должна существовать.

7. Не называй проблему, если не можешь показать,
   чем именно код создаёт проблему.

8. Если подтверждённых проблем нет — прямо напиши это.

9. Предположения обязательно отделяй от подтверждённых фактов.

10. Если недостаточно информации для вывода,
    напиши "Недостаточно данных для подтверждения".

11. Не придумывай рекомендации ради заполнения ответа.
    Рекомендация должна быть связана с конкретной проблемой.

ФОРМАТ ОТВЕТА:

### 1. Назначение
Что делает анализируемая функция.

### 2. Логика работы
Краткая последовательность действий функции.

### 3. Подтверждённые проблемы
Только проблемы, которые непосредственно подтверждаются кодом.

Для каждой:
- Проблема
- Доказательство
- Последствие

Если проблем нет:
"Подтверждённых проблем в предоставленном коде не обнаружено."

### 4. Предположения
Только то, что невозможно подтвердить по предоставленному коду.

Если предположений нет:
"Предположений нет."

### 5. Рекомендации
Только обоснованные изменения.

Если изменения не нужны:
"Обоснованных изменений по результатам анализа не требуется."

### 6. Итог
Краткий технический вывод.

Не используй приветствия.
Не задавай вопросов.
Не обращайся к пользователю.
Не предлагай дальнейшую помощь.

КОД:

----- НАЧАЛО ФАЙЛА -----
{content}
----- КОНЕЦ ФАЙЛА -----
"""

    analysis = ai.ask(
        prompt,
        add_to_history=False
    )

    return {
        "success": True,
        "filename": filename,
        "analysis": analysis
    }